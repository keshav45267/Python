# Creating a tuple with multiple elements
my_tuple = (1, 2, 3, 4, 5)

# Unpacking the tuple into individual variables
a, b, c, d, e = my_tuple

# Printing the variables to check the values
print("Values after unpacking:")
print("a =", a)
print("b =", b)
print("c =", c)
print("d =", d)
print("e =", e)
